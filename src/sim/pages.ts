export const pageParId = (id: string) => PAGES.find((p) => p.id === id);

export function carteDePage(p: Page): Carte {
  return lireCarte(`${p.id} ${p.nom}`, p.carte, p.papier);
}

export interface Choix {
  toursDispo: TypeTour[];
  colle: boolean;
  talents?: Talents;
  defi?: Defi;
  sansFin?: boolean;
}

export function optionsDePage(p: Page, c: Choix): Options {
  const carte = carteDePage(p);
  return {
    carte,
    regles: { graine: hashString("page-" + p.id), total: c.sansFin ? Infinity : p.vagues, pool: p.pool, difficulte: p.difficulte * (c.sansFin ? 1.1 : 1), boss: p.boss, entrees: carte.entrees.length },
    encreDepart: p.encre,
    toursDispo: c.toursDispo,
    gestes: { mur: true, rature: true, colle: c.colle },
    talents: c.talents,
    defi: c.defi,
  };
}

/** La page du jour : carte générée, 20 vagues, tous les monstres, toutes les tours, sans talents. */
export function optionsPageDuJour(graine: string, toutes: TypeTour[]): Options {
  const g = hashString("jour-" + graine);
  const carte = genererCarte(g);
  return {
    carte,
    regles: {
      graine: g, total: 20, difficulte: 1.05, boss: (["mere", "compas", "taille"] as const)[g % 3], entrees: carte.entrees.length,
      pool: ["gribouille", "carre", "avion", "araignee", "postit", "tache", "fantome", "punaise", "tippex", "gomme"],
    },
    encreDepart: 160,
    toursDispo: toutes,
  };
}
